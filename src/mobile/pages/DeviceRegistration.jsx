import React, { useState } from 'react';
import { mobileGatewayService } from '../services/mobileApi';
import { Smartphone, ShieldCheck, KeyRound, AlertCircle, ArrowRight } from 'lucide-react';

export default function DeviceRegistration({ onRegistered }) {
  const [deviceName, setDeviceName] = useState('My Android Device');
  const [platform, setPlatform] = useState('Android');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);

  const handleSubmit = async (e) => {
    e.preventDefault();
    if (!deviceName.trim()) return;

    try {
      setLoading(true);
      setError(null);
      const res = await mobileGatewayService.registerDevice({
        device_name: deviceName.trim(),
        platform: platform,
        app_version: '1.0.0',
      });
      // Store in client storage
      localStorage.setItem('nxs_mobile_device', JSON.stringify(res));
      onRegistered(res);
    } catch (err) {
      setError(err.message || 'Registration failed. Check connection to Central Ubuntu Server.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="min-h-[80vh] flex flex-col justify-center px-4 max-w-md mx-auto">
      <div className="bg-[#0D121C] border border-[#162132] p-6 rounded-2xl shadow-xl space-y-6">
        <div className="text-center space-y-2">
          <div className="w-14 h-14 bg-[#00D4FF]/10 border border-[#00D4FF]/30 rounded-2xl mx-auto flex items-center justify-center text-[#00D4FF]">
            <Smartphone className="w-7 h-7" />
          </div>
          <h1 className="text-xl font-bold tracking-tight text-[#F4F7FB]">
            Register Mobile Agent
          </h1>
          <p className="text-xs text-[#8995A7]">
            Connect this device to the NEXSHIELD Central Security Gateway
          </p>
        </div>

        {error && (
          <div className="p-3 bg-[#FF4545]/10 border border-[#FF4545]/30 rounded-lg text-xs text-[#FF4545] flex items-center gap-2">
            <AlertCircle className="w-4 h-4 shrink-0" />
            <span>{error}</span>
          </div>
        )}

        <form onSubmit={handleSubmit} className="space-y-4">
          <div>
            <label className="block text-xs font-medium text-[#8995A7] mb-1">
              Device Identifier Name
            </label>
            <input
              type="text"
              required
              value={deviceName}
              onChange={(e) => setDeviceName(e.target.value)}
              placeholder="e.g. Pixel 8 Field Agent"
              className="w-full bg-[#080B12] border border-[#162132] px-3.5 py-2.5 rounded-lg text-xs text-[#F4F7FB] focus:outline-none focus:border-[#00D4FF]"
            />
          </div>

          <div>
            <label className="block text-xs font-medium text-[#8995A7] mb-1">
              Client Platform
            </label>
            <select
              value={platform}
              onChange={(e) => setPlatform(e.target.value)}
              className="w-full bg-[#080B12] border border-[#162132] px-3.5 py-2.5 rounded-lg text-xs text-[#F4F7FB] focus:outline-none focus:border-[#00D4FF]"
            >
              <option value="Android">Android Mobile (PWA)</option>
              <option value="iOS">iOS (Field Client)</option>
              <option value="Linux-Terminal">Linux Field Client</option>
            </select>
          </div>

          <div className="p-3 bg-[#080B12] rounded-lg border border-[#162132] text-[11px] text-[#8995A7] space-y-1">
            <div className="flex items-center gap-1.5 text-[#19E68C] font-semibold">
              <ShieldCheck className="w-3.5 h-3.5" />
              Cryptographic Credentials
            </div>
            <p>
              A revocable API secret key will be generated by Ubuntu Central and saved in secure client storage.
            </p>
          </div>

          <button
            type="submit"
            disabled={loading}
            className="w-full bg-[#00D4FF] hover:bg-[#00B4D8] active:scale-98 text-[#080B12] font-bold py-3 rounded-xl text-xs tracking-wider transition flex items-center justify-center gap-2 shadow-[0_0_20px_rgba(0,212,255,0.25)]"
          >
            {loading ? 'Registering Device...' : (
              <>
                Register Agent
                <ArrowRight className="w-4 h-4" />
              </>
            )}
          </button>
        </form>
      </div>
    </div>
  );
}

